/** Device name for a node's hardware model, or null when it never reported one. */
export function hardwareName(hwModel) {
  if (!Number.isInteger(hwModel) || hwModel <= 0) return null;
  return HARDWARE_NAMES[hwModel] ?? `Hardware ${hwModel}`;
}

